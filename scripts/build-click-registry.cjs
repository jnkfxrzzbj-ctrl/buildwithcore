/* Exact allowed tuples from public, rendered links. No visitor-supplied dimensions. */
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const decode=s=>s.replace(/&amp;/g,'&').replace(/&quot;/g,'"').replace(/&#39;/g,"'").replace(/&lt;/g,'<').replace(/&gt;/g,'>');
const rows=[];
for(const page of ['core-starter.html','core-performance.html','core-high-end.html','core-starter-guide.html','core-high-end-guide.html']){
 for(const tag of fs.readFileSync(path.join(root,page),'utf8').matchAll(/<a\b[^>]*data-core-build=[^>]*>/g)){
  const attrs=Object.fromEntries([...tag[0].matchAll(/([\w-]+)="([^"]*)"/g)].map(m=>[m[1],decode(m[2])]));
  rows.push([attrs['data-core-build'],attrs['data-core-component'],attrs['data-core-retailer'],attrs['data-core-link-type'],page]);
 }
}
const output='// Generated by scripts/build-click-registry.cjs\nexport default '+JSON.stringify([...new Set(rows.map(JSON.stringify))].map(JSON.parse),null,2)+';\n';
const file=path.join(root,'analytics/registry.mjs');
if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==output)throw Error('Stale click registry');}else fs.writeFileSync(file,output);
